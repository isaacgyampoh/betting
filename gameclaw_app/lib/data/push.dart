import 'dart:async';

import 'package:firebase_messaging/firebase_messaging.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter_local_notifications/flutter_local_notifications.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import 'api_client.dart';
import 'providers.dart';

/// Native push, via Firebase Cloud Messaging.
///
/// The whole design hangs off one fact: the identifier Firebase gives us belongs to an *install*,
/// not to a sign-in. The same phone keeps the same id whoever is signed in, so the server stores
/// it uniquely and re-registering reassigns the row. That is what stops a second user on a shared
/// phone inheriting the first one's alerts, and it is why this registers on sign-in and
/// unregisters on sign-out rather than trying to hold one id per account.
///
/// What is stored is the **FCM registration token**, from `getToken()`.
///
/// That call is deprecated in firebase_messaging 17 in favour of `register()`/`onRegistered`,
/// which hand back a Firebase Installation ID instead - and the deprecation is not followed here
/// on purpose. FCM's HTTP v1 `messages:send` documents its `token` field as the registration
/// token; whether it also accepts an installation id is not something to find out at send time,
/// when the failure looks like "notifications do not work" and nothing says why. The device did
/// register with an installation id first, and the server rejected it as too short - which is how
/// the mismatch surfaced at all.
///
/// `onTokenRefresh` is still the source of truth for changes: Firebase rotates a token on
/// reinstall and restore, and a rotation the server never hears about is a device that silently
/// stops receiving anything.
///
/// Nothing here assumes Firebase is configured. A build without google-services.json has no push
/// at all: every method returns quietly instead of throwing, because a missing optional feature
/// must not take the app down on launch.
class PushService {
  PushService({required this.ref});

  final Ref ref;

  FirebaseMessaging? _messaging;
  StreamSubscription<String>? _registered;
  StreamSubscription<RemoteMessage>? _foreground;
  StreamSubscription<RemoteMessage>? _opened;

  final _local = FlutterLocalNotificationsPlugin();

  /// Where a tapped notification wants to go. Read by the router once it exists - a tap can
  /// arrive before the first frame, and the route would otherwise be lost.
  final pendingRoute = ValueNotifier<String?>(null);

  /// The channel Android groups these under. Must exist before the first notification, or
  /// Android silently drops it on 8.0 and later.
  ///
  /// The id carries a version, and that is not decoration. A notification channel's sound,
  /// importance and vibration are fixed the moment it is first created: changing them in code
  /// afterwards does nothing at all, for ever, on every device that already has it. Adding the
  /// custom sound therefore needs a new id, and the old one is deleted below so nobody is left
  /// on a channel that still plays the system default.
  static const _channelId = 'gameclaw_matches_v2';

  /// The channel this replaces. Deleted on startup so it stops appearing in Android settings.
  static const _retiredChannelId = 'gameclaw_matches';

  static const _channel = AndroidNotificationChannel(
    _channelId,
    'Match alerts',
    description: 'Kick-off, goals and full time for teams you follow.',
    importance: Importance.high,
    // res/raw/gameclaw_alert.wav, by resource name. Generated by tool/make_notification_sound.py
    // rather than sampled, so there is no licence question about it.
    sound: RawResourceAndroidNotificationSound('gameclaw_alert'),
    playSound: true,
    enableVibration: true,
  );

  /// The id currently known to the server, so the same one is not sent twice.
  String? _sent;

  /// The id being sent right now, so two callers cannot send it at once.
  String? _sending;

  /// True once Firebase has initialised. False in a build with no Firebase configuration.
  bool get available => _messaging != null;

  /// Call once, after Firebase.initializeApp has succeeded.
  Future<void> attach(FirebaseMessaging messaging) async {
    _messaging = messaging;
    // ignore: deprecated_member_use
    _registered = messaging.onTokenRefresh.listen(_send);

    await _local.initialize(
      settings: const InitializationSettings(
        android: AndroidInitializationSettings('@mipmap/ic_launcher'),
        // iOS asks for the notification permission at initialise time unless told not to, and
        // being asked on first launch - before anything has been explained - is the prompt most
        // people refuse for ever. All three are false so the ask stays where Android's already
        // is: in `requestPermission`, when the user turns alerts on.
        iOS: DarwinInitializationSettings(
          requestAlertPermission: false,
          requestBadgePermission: false,
          requestSoundPermission: false,
        ),
      ),
      onDidReceiveNotificationResponse: (response) => _open(response.payload),
    );
    // Null on iOS, where channels do not exist: the resolver returns the implementation only on
    // the platform it belongs to, so this whole block is simply skipped there.
    final android = _local
        .resolvePlatformSpecificImplementation<AndroidFlutterLocalNotificationsPlugin>();
    // Retire the old channel first. Leaving it behind means a second "Match alerts" entry in
    // Android settings, one of which silently plays the default sound.
    await android?.deleteNotificationChannel(channelId: _retiredChannelId);
    await android?.createNotificationChannel(_channel);

    // Both platforms deliver to `onMessage` without drawing anything while the app is in the
    // foreground - Android because it only posts when backgrounded, iOS because a foreground
    // notification is suppressed unless presentation options are set. Drawing it here covers
    // both, and is why those options are deliberately not set: the system and this would
    // otherwise each post one, and the user would see the same goal twice.
    _foreground = FirebaseMessaging.onMessage.listen(_showForeground);

    // Tapped while the app was running in the background.
    _opened = FirebaseMessaging.onMessageOpenedApp.listen((m) => _open(m.data['route'] as String?));

    // Tapped while the app was not running at all: the message that launched it is waiting here,
    // and is only delivered once.
    final initial = await messaging.getInitialMessage();
    if (initial != null) _open(initial.data['route'] as String?);
  }

  void _open(String? route) {
    if (route == null || route.isEmpty) return;
    pendingRoute.value = route;
  }

  Future<void> _showForeground(RemoteMessage message) async {
    final notification = message.notification;
    if (notification == null) return;
    await _local.show(
      // Collapsing on the key means a goal confirmed twice replaces itself rather than stacking.
      id: message.collapseKey?.hashCode ?? notification.hashCode,
      title: notification.title,
      body: notification.body,
      notificationDetails: NotificationDetails(
        android: AndroidNotificationDetails(
          _channel.id,
          _channel.name,
          channelDescription: _channel.description,
          importance: Importance.high,
          priority: Priority.high,
          // The same sound the channel declares. Android uses the channel's on 8.0+, but a
          // device below that reads it from here, and they must not differ.
          sound: const RawResourceAndroidNotificationSound('gameclaw_alert'),
        ),
        // The same alert, converted from the Android asset and bundled as a resource of the
        // Runner target - iOS reads a notification sound from the app bundle, not from Flutter's
        // assets, so `ios/Runner/gameclaw_alert.caf` is listed in the Xcode project rather than
        // in pubspec.yaml. Naming a file that is not bundled makes iOS fall silent rather than
        // fall back to the default, which reads as a broken alert, so the name and the build
        // phase have to move together.
        //
        // This covers the notification drawn here, in the foreground. One arriving while the app
        // is backgrounded is drawn by iOS from the APNs payload, and takes its sound from there.
        iOS: const DarwinNotificationDetails(
          presentAlert: true,
          presentBadge: true,
          presentSound: true,
          sound: 'gameclaw_alert.caf',
        ),
      ),
      payload: message.data['route'] as String?,
    );
  }

  Future<void> dispose() async {
    await _registered?.cancel();
    await _foreground?.cancel();
    await _opened?.cancel();
    _registered = null;
    _foreground = null;
    _opened = null;
    pendingRoute.dispose();
  }

  /// Asks for the notification permission, on both platforms.
  ///
  /// Android 13+ requires it; iOS has always required it. Asked when the user turns alerts on,
  /// not at launch: a permission prompt on first open, before anything has been explained, is
  /// the one most people refuse for ever.
  ///
  /// On iOS this is also what triggers APNs registration, and the FCM token is not available
  /// until APNs has handed one over - so on iOS `getToken()` before this returns null rather
  /// than failing, which is why registration follows the permission rather than preceding it.
  Future<bool> requestPermission() async {
    final messaging = _messaging;
    if (messaging == null) return false;
    final settings = await messaging.requestPermission();
    return _granted(settings.authorizationStatus);
  }

  Future<bool> hasPermission() async {
    final messaging = _messaging;
    if (messaging == null) return false;
    return _granted((await messaging.getNotificationSettings()).authorizationStatus);
  }

  static bool _granted(AuthorizationStatus status) =>
      status == AuthorizationStatus.authorized || status == AuthorizationStatus.provisional;

  /// Registers this install against the signed-in user. The id arrives on [onRegistered].
  Future<void> register() async {
    final messaging = _messaging;
    if (messaging == null) return;
    if (ref.read(sessionProvider).value == null) return;
    try {
      // ignore: deprecated_member_use
      final token = await messaging.getToken();
      if (token != null) await _send(token);
    } on Exception catch (error) {
      // Push is optional and this runs from a toggle. A platform error here must not reach the
      // framework as an unhandled exception - the user gets a switch that does not stick, which
      // is bad, rather than a red screen, which is worse.
      debugPrint('push: register failed ($error)');
    }
  }

  /// Removes this device's registration, server side and at Firebase.
  ///
  /// Both halves matter. The server stops addressing this install, and unregistering at Firebase
  /// means the next person to sign in on this phone gets a fresh id rather than inheriting one.
  Future<void> unregister() async {
    final messaging = _messaging;
    // ignore: deprecated_member_use
    final id = _sent ?? await messaging?.getToken();
    _sent = null;

    if (id != null) {
      try {
        await ref
            .read(apiClientProvider)
            .delete<Map<String, dynamic>>('/devices', body: {'token': id});
      } on ApiFailure catch (error) {
        debugPrint('push: could not unregister device (${error.message})');
      }
    }

    try {
      // Deleting the token forces Firebase to issue a fresh one, so the next person to sign in on
      // this phone cannot inherit this subscription even briefly.
      // ignore: deprecated_member_use
      await messaging?.deleteToken();
    } on Exception catch (error) {
      // Nothing useful to do here: removing the row server side, above, is what actually stops
      // delivery. This only releases the token at Firebase.
      debugPrint('push: deleting the token at Firebase failed ($error)');
    }
  }

  /// Asks the server to send this account a notification, and reports what it says.
  ///
  /// Returns null on success, or the server's own explanation - it knows whether no device is
  /// registered, whether the registration is dead, or whether sending is configured at all, and
  /// any of those is more useful than "something went wrong".
  Future<String?> sendTest() async {
    try {
      await ref.read(apiClientProvider).post<Map<String, dynamic>>('/devices/test');
      return null;
    } on ApiFailure catch (error) {
      return error.message;
    }
  }

  Future<void> _send(String id) async {
    if (id == _sent || id == _sending) return;
    if (ref.read(sessionProvider).value == null) return;
    // Claimed before the request rather than after it. On the device both the launch listener and
    // onTokenRefresh fired with the same token and neither had finished when the other started,
    // so the server saw it twice. Harmless - the upsert is idempotent - but it is still two round
    // trips to say the same thing.
    _sending = id;
    try {
      await ref
          .read(apiClientProvider)
          .post<Map<String, dynamic>>('/devices', body: {'token': id, 'platform': 'android'});
      _sent = id;
    } on ApiFailure catch (error) {
      // Best effort. Failing this must never block sign-in or break a screen; the next launch,
      // or the next rotation, tries again.
      debugPrint('push: could not register device (${error.message})');
    } finally {
      _sending = null;
    }
  }
}

final pushServiceProvider = Provider<PushService>((ref) {
  final service = PushService(ref: ref);
  ref.onDispose(service.dispose);
  return service;
});
